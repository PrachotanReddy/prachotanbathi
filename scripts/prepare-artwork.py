"""Optimize approved image-generation outputs; originals and prompts are preserved."""
import json
from pathlib import Path
from PIL import Image, ImageOps, ImageEnhance

root = Path(__file__).resolve().parent.parent
source = root / 'output' / 'imagegen'
target = root / 'public' / 'forest'
originals = sorted(source.glob('*.png'))
if not originals:
    raise SystemExit('No originals in output/imagegen/. Existing optimized assets are ready to use; a normal build does not need this step.')
target.mkdir(parents=True, exist_ok=True)
names = []
for path in originals:
    name = path.stem
    outputs = [target / f'{name}.webp']
    if name.startswith('forest-day'):
        outputs.append(target / f'{name.replace("day", "night")}.webp')
    elif not name.startswith('forest-'):
        outputs.append(target / f'{name}-small.webp')
    if all(p.exists() and p.stat().st_size and p.stat().st_mtime >= path.stat().st_mtime for p in outputs):
        names.append(name)
        if name.startswith('forest-day'):
            names.append(name.replace('day', 'night'))
        continue
    image = Image.open(path).convert('RGBA')
    background = name.startswith('forest-')
    if background:
        image = image.convert('RGB')
        image.thumbnail((1536, 1536), Image.Resampling.LANCZOS)
    else:
        alpha = image.getchannel('A')
        if alpha.getextrema()[0] != 0:
            raise ValueError(f'{name}: expected a genuinely transparent background')
        bounds = alpha.point(lambda value: 255 if value > 8 else 0).getbbox()
        if not bounds:
            raise ValueError(f'{name}: empty artwork')
        image = image.crop(bounds)
        canvas_size = (640, 440) if name in ('bear', 'bear-beer', 'fern', 'branch', 'log', 'rock') else (640, 640)
        image.thumbnail((round(canvas_size[0] * .94), round(canvas_size[1] * .94)), Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA', canvas_size)
        canvas.alpha_composite(image, ((canvas_size[0] - image.width) // 2, (canvas_size[1] - image.height) // 2))
        image = canvas
    image.save(target / f'{name}.webp', quality=86 if background else 84, method=4)
    if name in ('forest-day', 'forest-day-portrait'):
        # A deterministic grade preserves exact registration across the crossfade.
        luminance = ImageOps.grayscale(image)
        night = ImageOps.colorize(luminance, black='#061c1c', white='#46676e', mid='#173c3d')
        night = Image.blend(night, ImageEnhance.Brightness(image).enhance(.3), .12)
        night_name = name.replace('day', 'night')
        night.save(target / f'{night_name}.webp', quality=86, method=4)
        names.append(night_name)
    if not background:
        image.thumbnail((320, 320), Image.Resampling.LANCZOS)
        image.save(target / f'{name}-small.webp', quality=80, method=4)
    names.append(name)
(root / 'src' / 'artwork.js').write_text('// Generated by scripts/prepare-artwork.py. Originals: output/imagegen/.\nexport const generatedArt = new Set(' + json.dumps(names) + ');\n')
print(f'Prepared {len(names)} artwork assets ({sum(p.stat().st_size for p in target.glob("*.webp")) / 1024:.0f} KiB including responsive variants).')
